const FEET = {
  down: ['....xwxwxwxw....', '.....f....f.....'],
  downL: ['...xwxwx.xwxw...', '....f......f....'],
  downR: ['...xwxw.xwxwx...', '......f....f....'],
  up: ['....xwxwxwxw....', '.....f....f.....'],
  upL: ['...xwxwx.xwxw...', '....f......f....'],
  upR: ['...xwxw.xwxwx...', '......f....f....'],
  right: ['......xxkkxx....', '.......f..f.....'],
  rightL: ['.....xxkkxx.....', '......f....f....'],
  rightR: ['......xxkkxx....', '.......f..f.....'],
};

function withFeet(base, key) {
  const copy = base.slice();
  const [a, b] = FEET[key];
  copy[22] = a;
  copy[23] = b;
  return copy;
}

function bob(rows, dy) {
  if (!dy) return rows;
  const blank = '.'.repeat(rows[0].length);
  if (dy < 0) return [blank, ...rows.slice(0, -1)];
  return [...rows.slice(1), blank];
}

/** 4-frame walk. Frames 1 and 3 bob the head. */
export function frameRows(facing, frame) {
  const f = frame % 4;
  if (facing === 'up') {
    const step = f === 1 ? 'upL' : f === 3 ? 'upR' : 'up';
    return bob(withFeet(UP, step), f === 1 || f === 3 ? -1 : 0);
  }
  if (facing === 'right' || facing === 'left') {
    const step = f === 1 ? 'rightL' : f === 3 ? 'rightR' : 'right';
    return bob(withFeet(RIGHT, step), f === 1 || f === 3 ? -1 : 0);
  }
  const step = f === 1 ? 'downL' : f === 3 ? 'downR' : 'down';
  return bob(withFeet(DOWN, step), f === 1 || f === 3 ? -1 : 0);
}

export function drawSprite(ctx, sprite, x, y, scale, flip) {
  const h = sprite.length;
  const w = sprite[0].length;
  for (let py = 0; py < h; py++) {
    const row = sprite[py];
    for (let px = 0; px < w; px++) {
      const ch = row[flip ? w - 1 - px : px];
      const color = PALETTE[ch];
      if (!color) continue;
      ctx.fillStyle = color;
      ctx.fillRect(x + px * scale, y + py * scale, scale, scale);
    }
  }
}
